/**
 * 룸 티어별 전용 유물 5종을 무작위 셔플하여 추출하는 함수 (중복 출품 0% 보장)
 */
export const createTierItemQueue = (tier: RoomTier): Item[] => {
  const tierItems = MASTER_ITEMS.filter((item) => item.tier === tier);
  if (tierItems.length < 5) {
    throw new Error(`[ItemPool] Insufficient items for tier ${tier}. Found: ${tierItems.length}`);
  }

  // Fisher-Yates 비복원 셔플
  const shuffled = [...tierItems].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, 5).map((item) => {
    const isFake = Math.random() < (tier === 'DIAMOND' || tier === 'BLACK_MARKET' ? 0.10 : 0.18);
    
    // 유물 보존 상태 3종 랜덤 분배 (40% Pristine, 40% Dusty, 20% Damaged)
    const rand = Math.random();
    const condition = rand < 0.40 ? 'PRISTINE' : rand < 0.80 ? 'DUSTY' : 'DAMAGED';
    const conditionMultiplier = condition === 'PRISTINE' ? 1.0 : condition === 'DUSTY' ? 0.8 : 0.5;
    const tierCost = tier === 'BRONZE' ? 400 : tier === 'SILVER' ? 1200 : tier === 'GOLD' ? 3500 : tier === 'DIAMOND' ? 12000 : 20000;

    return {
      ...item,
      condition,
      conditionMultiplier,
      restorationCost: item.restorationCost || tierCost,
      isFake,
      realValue: isFake ? 0 : item.realValue,
      isAppraised: false
    };
  });
};
